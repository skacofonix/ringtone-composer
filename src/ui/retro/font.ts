/** Typographic characters drawn with a plain equivalent. */
const SUBSTITUTES: Record<string, string> = {
  '’': "'",
  '‘': "'",
  '“': '"',
  '”': '"',
  '«': '"',
  '»': '"',
  '–': '-',
  '—': '-',
  ᵉ: 'e',
};

export const GLYPH_HEIGHT = 7;
const SPACE_WIDTH = 2;
/** Blank pixel column between two glyphs. */
const LETTER_SPACING = 1;

export interface Glyph {
  readonly rows: readonly number[];
  /** First used column (0 = leftmost) and number of used columns. */
  readonly left: number;
  readonly width: number;
}

const cache = new Map<string, Glyph>();

/** The glyph of a character; accents are dropped, unknown characters give `?`. */
export function glyph(char: string): Glyph {
  let result = cache.get(char);
  if (!result) {
    const base = (SUBSTITUTES[char] ?? char)
      .normalize('NFD')
      .replace(/\p{Diacritic}/gu, '');
    const rows = char === ' ' ? null : (GLYPHS[base] ?? GLYPHS['?']!);
    result = rows ? measure(rows) : { rows: [], left: 0, width: SPACE_WIDTH };
    cache.set(char, result);
  }
  return result;
}

/** Width in pixels of a text, as drawn by `drawText`. */
export function textWidth(text: string): number {
  let width = 0;
  for (const char of text) width += glyph(char).width + LETTER_SPACING;
  return Math.max(0, width - LETTER_SPACING);
}

export function advance(char: string): number {
  return glyph(char).width + LETTER_SPACING;
}

function measure(rows: readonly number[]): Glyph {
  const used = rows.reduce((acc, row) => acc | row, 0);
  let left = 0;
  while (left < 5 && !(used & (0x10 >> left))) left++;
  let right = 4;
  while (right > left && !(used & (0x10 >> right))) right--;
  return { rows, left, width: right - left + 1 };
}
